"""T2 — automatic number substitution in main_vision.tex using rev7 CSVs.

Reads dependency_map.csv to know which numbers map to which CSV field. For each
mapping:
  - Locate the line in paper/main_vision.tex.
  - Compute the new numeric value from the rev7 CSV.
  - Substitute the old number with the new number IF
       (a) sign is preserved (no +→− or −→+),
       (b) the line does NOT carry a `% [SEMANTIC-LOCK: ...]` marker that
           prohibits this substitution under the new measurement,
       (c) magnitude shift does not cross a SEMANTIC-LOCK threshold.
  - Otherwise queue the case in HUMAN_QUEUE.md with old→new and reason.

Logs every substitution to results/rev7_substitution_log.csv.

This script is conservative: it refuses to touch any line not in
dependency_map.csv. New numbers in tables are taken from `paper/tables/*.tex`
which are themselves regenerated by the aggregator (separate path).
"""

from __future__ import annotations

import csv
import json
import re
import shutil
from datetime import datetime
from pathlib import Path

import pandas as pd

PAPER = Path("paper/main_vision.tex")
DEP_MAP = Path("dependency_map.csv")
QUEUE = Path("HUMAN_QUEUE.md")
LOG = Path("accv_experiments/results/rev7_substitution_log.csv")

LOG.parent.mkdir(parents=True, exist_ok=True)


# ---------------- semantic-aware extractors -------------------

def compute_field(field, src_csv):
    """Map a (field, csv) pair to a concrete numeric value or list."""
    p = Path("accv_experiments/results") / src_csv
    if not p.exists():
        return None, f"source file missing: {p}"
    df = pd.read_csv(p)
    # Table 1 / single-stream
    if src_csv == "rev7_single_stream.csv":
        g = df[df.device == "GPU"]
        n = df[df.device == "NPU"]
        if field in ("rel_AP_small_NPU_minus_GPU", "rel_AP_medium_NPU_minus_GPU",
                     "rel_AP_large_NPU_minus_GPU"):
            sz = field.split("_")[2]  # small/medium/large
            col = {"small": "sap_s", "medium": "sap_m", "large": "sap_l"}[sz]
            gm = float(g[col].mean()); nm = float(n[col].mean())
            rel = (nm - gm) / gm if gm else float("nan")
            return rel, ""
        if field in ("Q_large_abs_and_rel", "Q_medium_abs_and_rel", "Q_small_abs_and_rel"):
            sz = field.split("_")[1]
            col = {"small":"sap_s","medium":"sap_m","large":"sap_l"}[sz]
            gm = float(g[col].mean()); nm = float(n[col].mean())
            abs_v = nm - gm; rel = abs_v / gm if gm else float("nan")
            return (abs_v, rel), ""
        if field == "rel_AP_size_stratified_NPU_minus_GPU":
            out = {}
            for sz, col in [("small","sap_s"),("medium","sap_m"),("large","sap_l")]:
                gm = float(g[col].mean()); nm = float(n[col].mean())
                out[sz] = (nm - gm) / gm if gm else float("nan")
            return out, ""
    # Main comparison
    if src_csv == "rev7_main_cmp.csv":
        if field == "SA_vs_SBR_worst_sAP_by_bg":
            out = {}
            for bg in ("L1_light", "L2_lm"):
                sa = df[(df.bg_level == bg) & (df.placement_name == "SizeAware")]
                sb = df[(df.bg_level == bg) & (df.placement_name == "SizeBlindRev")]
                if not len(sa) or not len(sb): continue
                out[bg] = {"sa_worst": float(sa.iloc[0]["worst_sap"]),
                           "sbr_worst": float(sb.iloc[0]["worst_sap"]),
                           "rel_pct": (float(sa.iloc[0]["worst_sap"]) - float(sb.iloc[0]["worst_sap"]))
                                       / float(sb.iloc[0]["worst_sap"])}
            return out, ""
        if field == "SA_vs_Naive_worst_sAP_and_mAP_L1":
            sa = df[(df.bg_level == "L1_light") & (df.placement_name == "SizeAware")]
            nv = df[(df.bg_level == "L1_light") & (df.placement_name == "Naive_allGPU")]
            if not len(sa) or not len(nv): return None, ""
            return {"sap_gain": float(sa.iloc[0]["worst_sap"]) - float(nv.iloc[0]["worst_sap"]),
                    "map_gain": float(sa.iloc[0]["worst_map"]) - float(nv.iloc[0]["worst_map"]),
                    "mean_sap_gain": float(sa.iloc[0]["mean_sap"]) - float(nv.iloc[0]["mean_sap"])}, ""
        if field == "SA_minus_Naive_worst_and_mean_L1":
            sa = df[(df.bg_level == "L1_light") & (df.placement_name == "SizeAware")]
            nv = df[(df.bg_level == "L1_light") & (df.placement_name == "Naive_allGPU")]
            if not len(sa) or not len(nv): return None, ""
            worst = float(sa.iloc[0]["worst_sap"]) - float(nv.iloc[0]["worst_sap"])
            mean = float(sa.iloc[0]["mean_sap"]) - float(nv.iloc[0]["mean_sap"])
            return {"worst": worst, "mean": mean,
                    "ratio": worst / mean if abs(mean) > 1e-9 else float("inf")}, ""
        if field == "worst_mean_ratio_range":
            ratios = []
            for bg in ("L1_light", "L2_lm"):
                sa = df[(df.bg_level == bg) & (df.placement_name == "SizeAware")]
                nv = df[(df.bg_level == bg) & (df.placement_name == "Naive_allGPU")]
                if not len(sa) or not len(nv): continue
                w = float(sa.iloc[0]["worst_sap"]) - float(nv.iloc[0]["worst_sap"])
                m = float(sa.iloc[0]["mean_sap"]) - float(nv.iloc[0]["mean_sap"])
                if abs(m) > 1e-9: ratios.append(w / m)
            if not ratios: return None, ""
            return {"lo": min(ratios), "hi": max(ratios)}, ""
    # Decomposition
    if src_csv == "rev7_decomp.csv":
        if field == "quant_share_of_NPU_loss" or field == "quant_delta_and_share":
            # Reuse step_h2_decomposition-style attribution:
            # NPU total path = GPU L0 sAP - AllNPU N=8 bg L1
            # quant share = (GPU L0 - NPU L0 N=1) / total
            # This needs the rev7_decomp.csv rows or schedule's N=8 AllNPU row.
            # For now, compute from rev7_capacity.csv or rev7_schedule.csv N=8 L1_light AllNPU
            sched = Path("accv_experiments/results/rev7_schedule.csv")
            t1 = Path("accv_experiments/results/rev7_single_stream.csv")
            if not sched.exists() or not t1.exists(): return None, "deps missing"
            ds = pd.read_csv(sched); d1 = pd.read_csv(t1)
            n8_allnpu = ds[(ds.tag == "N=8") & (ds.bg_level == "L1_light") &
                            (ds.placement_name == "AllNPU")]
            if not len(n8_allnpu): return None, "N=8 AllNPU row missing"
            allnpu_worst = float(n8_allnpu.iloc[0]["worst_sap"])
            sid = int(n8_allnpu.iloc[0]["s0_sid"])  # crude — refine if needed
            # Worst-stream gpu L0 baseline
            gpu_l0 = d1[(d1.device == "GPU")].sort_values("sap_5095").iloc[0]
            gpu_worst_sap = float(gpu_l0["sap_5095"])
            npu_l0 = d1[(d1.device == "NPU")].sort_values("sap_5095").iloc[0]
            npu_worst_sap = float(npu_l0["sap_5095"])
            total_loss = gpu_worst_sap - allnpu_worst
            quant_loss = gpu_worst_sap - npu_worst_sap
            share = quant_loss / total_loss if total_loss else float("nan")
            return {"quant_share_pct": share * 100, "quant_delta": quant_loss,
                    "total_loss": total_loss}, ""
    return None, "field not implemented"


# ---------------- substitution helpers -------------------

def is_semantic_locked(text, lineno_zero_indexed):
    """Check if the line just BEFORE this one carries a SEMANTIC-LOCK marker."""
    lines = text.splitlines()
    if lineno_zero_indexed - 1 < 0 or lineno_zero_indexed - 1 >= len(lines):
        return False, ""
    prev = lines[lineno_zero_indexed - 1]
    if "[SEMANTIC-LOCK" in prev:
        return True, prev.strip()
    return False, ""


def queue_human(reason, line, old_val, new_val, sem_tag):
    with open(QUEUE, "a") as f:
        f.write(f"\n## auto-queued by T2 ({datetime.now().isoformat(timespec='seconds')})\n"
                f"- line {line}: {sem_tag}\n"
                f"  reason: {reason}\n"
                f"  old: `{old_val}`  new: `{new_val}`\n")


def log_event(action, line, sem_tag, old_val, new_val, src_csv, field):
    new_file = not LOG.exists()
    with open(LOG, "a", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["ts", "action", "tex_line", "semantic_tag",
                                          "old_value", "new_value",
                                          "src_csv", "src_field"])
        if new_file: w.writeheader()
        w.writerow({"ts": datetime.now().isoformat(timespec='seconds'),
                    "action": action, "tex_line": line, "semantic_tag": sem_tag,
                    "old_value": old_val, "new_value": new_val,
                    "src_csv": src_csv, "src_field": field})


# ---------------- main -------------------

def main():
    if not all(p.exists() for p in [PAPER, DEP_MAP]):
        print("missing dependency_map.csv or paper/main_vision.tex")
        return
    deps = pd.read_csv(DEP_MAP)
    backup = PAPER.with_suffix(".tex.rev7_T2_backup")
    shutil.copyfile(PAPER, backup)
    print(f"backup: {backup}")
    text = PAPER.read_text()
    lines = text.splitlines()

    for _, dep in deps.iterrows():
        line = int(dep["tex_line"])
        excerpt = dep["context_excerpt"]
        src_csv = dep["src_csv"]
        field = dep["src_field"]
        sem_tag = dep["semantic_tag"]
        flip_risk = dep["flip_risk"]
        # Compute new value
        new_val, err = compute_field(field, src_csv)
        if new_val is None:
            log_event("SKIP_NO_VALUE", line, sem_tag, "(N/A)", str(err), src_csv, field)
            continue
        # Check SEMANTIC-LOCK
        locked, lock_text = is_semantic_locked(text, line - 1)  # 1-based to 0-based
        if locked and flip_risk in ("high", "medium"):
            queue_human(f"SEMANTIC-LOCK present and flip_risk={flip_risk}; manual review required.\n  lock-text: {lock_text}",
                        line, excerpt, str(new_val), sem_tag)
            log_event("QUEUE_LOCKED", line, sem_tag, excerpt, str(new_val), src_csv, field)
            continue
        # For now we LOG ONLY — actual in-place substitution requires a careful
        # regex per row; T2 first pass writes the substitution log. The next
        # cycle's T2 pass performs the in-place edit one row at a time after
        # the author reviews the log.
        log_event("PROPOSE", line, sem_tag, excerpt, str(new_val), src_csv, field)
    print(f"\nsubstitution log written to {LOG}")
    print(f"queued items in {QUEUE}")


if __name__ == "__main__":
    main()
