"""Aggregate rev10 measurements into results/rev10_summary.md.

Reads:
  results/rev10_gen_single.csv  (A-1)
  results/rev10_gen_gain.csv    (A-2 — 3 reps each)
  results/rev10_cstar.csv       (A-3)
  results/rev10_cstar_derived.csv (B-2 output, C* values)
  results/manifest_rev10.json   (GATE-Q, GATE-S verdicts, env)

Writes:
  results/rev10_summary.md
  results/rev10_a2_summary.csv (detector × bg × strategy → mean±std)

No measurement. No prose edits.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent.parent
RES = ROOT / "accv_experiments" / "results"
OUT_MD = RES / "rev10_summary.md"
OUT_A2 = RES / "rev10_a2_summary.csv"

DETECTORS = [("yolo11s", 9.4), ("yolo11m", 20.1),
              ("yolo11l", 25.3), ("yolo11x", 56.9)]
BG_ORDER = ["L0", "L1_light", "L1_heavy", "L2_lm", "L3_vlm"]


def fmt(v, prec=4):
    if v is None or (isinstance(v, float) and not np.isfinite(v)): return "—"
    return f"{v:+.{prec}f}" if isinstance(v, float) else str(v)


def main():
    manifest = json.loads((RES / "manifest_rev10.json").read_text())
    env = manifest.get("env_start", {})
    gate_q = manifest.get("gate_q", {})
    gate_s = manifest.get("gate_s", {})

    buf = []
    buf.append("# rev10 summary — §7 family in normal state\n\n")
    buf.append("_Generated by `phase_rev10_summary.py`. No measurement. No prose / table edits._\n\n")

    # Environment
    buf.append("## Environment\n\n")
    buf.append(f"- driver: `{env.get('driver','?')}`\n")
    buf.append(f"- gpu_util at start: `{env.get('gpu_util_pct','?')}%`\n")
    buf.append(f"- gpu_temp at start: `{env.get('gpu_temp_c','?')}°C`\n\n")

    # GATES
    buf.append("## Gates\n\n")
    if gate_q:
        ok = "**PASS**" if gate_q.get("pass") else "**FAIL**"
        buf.append(f"### GATE-Q  (yolo11s large rel gap = target {gate_q.get('target','?'):+.3f} "
                    f"± {gate_q.get('tol','?'):.3f})\n\n")
        buf.append(f"- gpu_l (mean over 24 logs) = `{gate_q.get('gpu_l',0):.4f}`\n")
        buf.append(f"- npu_l (mean over 24 logs) = `{gate_q.get('npu_l',0):.4f}`\n")
        buf.append(f"- rel gap = `{gate_q.get('rel',0):+.3f}`\n")
        buf.append(f"- result: {ok}\n\n")
    if gate_s:
        ok = "**PASS**" if gate_s.get("pass") else "**FAIL**"
        buf.append(f"### GATE-S  (yolo11s SA-SBR worst gain at L1_light = target "
                    f"{gate_s.get('target','?'):+.4f} ± {gate_s.get('tol','?'):.4f})\n\n")
        buf.append(f"- SA worst (mean over {gate_s.get('n_sa',0)} reps) = "
                    f"`{gate_s.get('sa_mean',0):.4f}`\n")
        buf.append(f"- SBR worst (mean over {gate_s.get('n_sbr',0)} reps) = "
                    f"`{gate_s.get('sbr_mean',0):.4f}`\n")
        buf.append(f"- gain = `{gate_s.get('gain',0):+.4f}`\n")
        buf.append(f"- result: {ok}\n\n")

    # A-1
    a1_path = RES / "rev10_gen_single.csv"
    if a1_path.exists():
        a1 = pd.read_csv(a1_path)
        buf.append("## A-1  Single-stream L0 per detector (24-log mean)\n\n")
        buf.append("| detector | params (M) | GPU sAP$_{S/M/L}$ | NPU sAP$_{S/M/L}$ | $\\Delta_S$ | $\\Delta_M$ | $\\Delta_L$ | rel $\\Delta_L$ |\n|---|---|---|---|---|---|---|---|\n")
        for det, pm in DETECTORS:
            sub = a1[a1.detector == det]
            g = sub[sub.device == "GPU"]; n = sub[sub.device == "NPU"]
            if not (len(g) and len(n)):
                buf.append(f"| {det} | {pm:.1f} | — | — | — | — | — | — |\n"); continue
            gs, gm, gl = g["sap_s"].mean(), g["sap_m"].mean(), g["sap_l"].mean()
            ns, nm, nl = n["sap_s"].mean(), n["sap_m"].mean(), n["sap_l"].mean()
            rel_l = (nl - gl) / gl if gl else float("nan")
            buf.append(f"| {det} | {pm:.1f} | "
                        f"{gs:.3f} / {gm:.3f} / {gl:.3f} | "
                        f"{ns:.3f} / {nm:.3f} / {nl:.3f} | "
                        f"`{ns-gs:+.3f}` | `{nm-gm:+.3f}` | `{nl-gl:+.3f}` | "
                        f"`{rel_l:+.3f}` |\n")
        buf.append("\n")

    # A-2 (multi-stream, 3 reps -> mean±std)
    a2_path = RES / "rev10_gen_gain.csv"
    if a2_path.exists():
        a2 = pd.read_csv(a2_path)
        buf.append("## A-2  Multi-stream N=4 Comp A (worst sAP mean±std over 3 reps)\n\n")
        rows_out = []
        for det, pm in DETECTORS:
            for bg in ["L1_light", "L2_lm"]:
                sub = a2[(a2.detector == det) & (a2.bg_level == bg)]
                if not len(sub): continue
                vals = {}
                for st in ["Naive_allGPU", "SizeAware", "SizeBlindRev", "AllNPU"]:
                    sr = sub[sub.placement_name == st]
                    vals[st] = {"worst_m": sr["worst_sap"].mean(),
                                 "worst_s": sr["worst_sap"].std(ddof=0) if len(sr) > 1 else 0.0,
                                 "mean_m":  sr["mean_sap"].mean(),
                                 "mean_s":  sr["mean_sap"].std(ddof=0) if len(sr) > 1 else 0.0,
                                 "n": int(len(sr))}
                rows_out.append({"detector": det, "bg": bg, **{
                    f"{st}_{k}": vals[st][k] for st in vals for k in vals[st]
                }})
        if rows_out:
            df = pd.DataFrame(rows_out)
            df.to_csv(OUT_A2, index=False)
            buf.append("Detail CSV: `results/rev10_a2_summary.csv`.\n\n")
        # Per-detector tables
        for det, pm in DETECTORS:
            sub = a2[a2.detector == det]
            if not len(sub): continue
            buf.append(f"### {det} ({pm:.1f} M)\n\n")
            buf.append("| bg | strategy | worst (mean±std) | mean (mean±std) | n reps |\n|---|---|---|---|---|\n")
            for bg in ["L1_light", "L2_lm"]:
                for st in ["Naive_allGPU", "SizeAware", "SizeBlindRev", "AllNPU"]:
                    sr = sub[(sub.bg_level == bg) & (sub.placement_name == st)]
                    if not len(sr): continue
                    wm = sr["worst_sap"].mean(); ws = sr["worst_sap"].std(ddof=0) if len(sr) > 1 else 0.0
                    mm = sr["mean_sap"].mean(); ms = sr["mean_sap"].std(ddof=0) if len(sr) > 1 else 0.0
                    buf.append(f"| {bg} | {st} | `{wm:.4f}±{ws:.4f}` | `{mm:.4f}±{ms:.4f}` | {len(sr)} |\n")
            # gain table
            buf.append("\nDerived gains (SA−SBR and SA−Naive):\n\n")
            buf.append("| bg | SA worst | SBR worst | Naive worst | SA−SBR worst | SA−Naive worst |\n|---|---|---|---|---|---|\n")
            for bg in ["L1_light", "L2_lm"]:
                row_sub = sub[sub.bg_level == bg]
                sa = row_sub[row_sub.placement_name == "SizeAware"]["worst_sap"]
                sbr = row_sub[row_sub.placement_name == "SizeBlindRev"]["worst_sap"]
                naive = row_sub[row_sub.placement_name == "Naive_allGPU"]["worst_sap"]
                if not (len(sa) and len(sbr) and len(naive)): continue
                sa_m = sa.mean(); sbr_m = sbr.mean(); na_m = naive.mean()
                buf.append(f"| {bg} | `{sa_m:.4f}` | `{sbr_m:.4f}` | `{na_m:.4f}` | "
                            f"`{sa_m-sbr_m:+.4f}` | `{sa_m-na_m:+.4f}` |\n")
            buf.append("\n")

    # A-3 / C*
    cstar_d = RES / "rev10_cstar_derived.csv"
    if cstar_d.exists():
        df = pd.read_csv(cstar_d)
        buf.append("## A-3  C$^\\star$ table (linear interpolation across bg ladder)\n\n")
        buf.append("| detector | group | C$^\\star$ (bg index) | bg interpretation |\n|---|---|---|---|\n")
        for _, r in df.iterrows():
            cs = r.get("cstar_bg_index")
            cs_str = f"{cs:.2f}" if cs is not None and np.isfinite(cs) else "no crossing"
            if cs is not None and np.isfinite(cs):
                lo = int(np.floor(cs)); hi = min(lo + 1, len(BG_ORDER) - 1)
                frac = cs - lo
                bg_interp = f"{BG_ORDER[lo]} → {BG_ORDER[hi]} ({frac:.0%})"
            else:
                bg_interp = "—"
            buf.append(f"| {r['detector']} | {r['group']} | {cs_str} | {bg_interp} |\n")
        buf.append("\nIndex map: " + ", ".join(f"`{i}={b}`" for i, b in enumerate(BG_ORDER)) + ".\n\n")

    # Figure-to-table cell-match notes
    buf.append("## Figure provenance (cell-match)\n\n")
    buf.append("- `paper/figures/motiv_reversal.pdf` (Fig. reversal, §5.2) — generated by "
                "`accv_experiments/scripts/phase_rev10_b1_motiv_reversal.py`, "
                "cell-matched against `paper/tables/partA.tex` (overall PASS).\n")
    buf.append("- `paper/figures/gen_cstar.pdf` (Fig. gen-cstar, §7) — generated by "
                "`accv_experiments/scripts/phase_rev10_b2_gen_cstar.py`, derives C$^\\star$ "
                "from `rev10_gen_single.csv` + `rev10_cstar.csv`.\n")
    vfp = ROOT / "paper" / "figures" / "vis_failure_examples.pdf"
    if vfp.exists():
        buf.append("- `paper/figures/vis_failure_examples.pdf` (Fig. failures, §5.1) — generated by "
                    "`accv_experiments/scripts/phase_vis_failure_examples.py`.\n")
    else:
        buf.append("- `paper/figures/vis_failure_examples.pdf` — **NOT generated** (see results/rev10_figs.md if present).\n")
    buf.append("\n")

    buf.append("---\n\n")
    buf.append("_End of summary. main_vision.tex and all paper/tables/*.tex NOT modified._\n")

    OUT_MD.write_text("".join(buf))
    print(f"saved {OUT_MD}")
    if OUT_A2.exists():
        print(f"saved {OUT_A2}")


if __name__ == "__main__":
    main()
