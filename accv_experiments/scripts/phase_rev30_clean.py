"""rev30 — CLEAN, SINGLE-RUN ResNet50 contention axis for the paper.

Replaces 4 scattered runs (tab:main=rev21/rev20, Fig3a=rev24/rev22, Fig3b=rev29,
Fig2=rev25/sweep_rerun) with ONE canonical measurement set, from which all tables
and figures are generated by code (no hand transcription).

Independent variable = co-tenant count k (ResNet50 GPU-pressure). Frame skip is a
DEPENDENT variable (it wanders 31/35/38/42% across runs near the 33.333ms deadline);
we therefore FIX k and repeat, with extra reps at the boundary (k=1) to quantify
its variance — the boundary statistics are a primary deliverable, not a weakness.

Reuses the EXISTING harness primitives unchanged:
  fg_worker, per_stream_sap, stop_background        (_step_d_common)   [core, untouched]
  start_bg_custom, _bg_resnet50_loop                (step_h2_robustness)
  FGModelGPUGeneric, load_npu_engines, ...          (phase_rev6_sweep)
`measure_multistream_full` below is a VERBATIM copy of
phase_rev6_sweep.measure_multistream with two additions and one removal:
  + keeps per_stream_sap's eff_mean_ms / sap_small/medium/large (for deadline
    margin + per-size), + returns median/p10 sAP; - drops per_stream_map_offline
    (offline mAP, unused here). Equivalence vs the stock function is asserted on
    the k=0 smoke cell (worst/mean/skip/sap_l within noise).

NPU mode = DET["multistream_mode"] = "single" THROUGHOUT (the established
multistream mode used by rev22=Fig3a, N=8-capable; NPU accuracy is mode-invariant,
so this also matches rev29's global8 All-NPU floor 0.0834 within noise). This
unifies the NPU mode across N=2/4/8 + the split sweep for the first time.

Deadline = 1000.0/FPS = 33.333ms (== _step_d_common period_ms).

Outputs (results/rev30_clean_resnet/ ; existing rev* untouched):
  rev30_raw.csv          canonical long-format, one row per (group,N,placement,k,rep),
                         incl. per_stream_json so Oracle candidates are recomputable.
  util_samples.csv       continuous pynvml samples (sliced per cell in aggregation).
  manifest_rev30.json    resume support.
Derived tables/figures are produced by phase_rev30_aggregate.py from rev30_raw.csv.
"""
