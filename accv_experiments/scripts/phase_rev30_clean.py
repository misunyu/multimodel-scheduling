def man():
    if MAN.exists():
        try: return json.loads(MAN.read_text())
        except Exception: pass
    return {"done": {}}
def save(m): MAN.write_text(json.dumps(m, indent=2))

def app(path, cols, row):
    new = not path.exists()
    with open(path, "a", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        if new: w.writeheader()
        w.writerow(row)

def reg_level(k):
    name = f"R30K{k}"; h2.BG_VARIANTS[name] = [_bg_resnet50_loop] * k; return name

def placement_for_ratio(r):
    """N=4 split: r streams on NPU, large-object streams moved first (rev29-identical)."""
    npu_set = set(MOVE_ORDER[:r])
    return ["NPU" if sid in npu_set else "GPU" for sid in PANEL4]

def pstr(placement):
    return "".join("N" if d == "NPU" else "G" for d in placement)


# ===== verbatim copy of phase_rev6_sweep.measure_multistream (+eff/per-size, -offline-mAP) =====
def measure_multistream_full(sids, splits, placement, gpu_models, npu_models, bg):
    n = len(placement)
    results = [defaultdict(list) for _ in range(n)]
    stop = threading.Event()
    bg_stops, bg_threads = start_bg_custom(bg)
    gpu_i = npu_i = 0
    threads = []
    for i, dev in enumerate(placement):
        if dev == "GPU":
            model = gpu_models[gpu_i]; gpu_i += 1
        elif dev == "NPU":
            model = npu_models[npu_i]; npu_i += 1
        else:
            raise ValueError(dev)
        t = threading.Thread(target=fg_worker,
                             args=(i, dev, splits[i], model, results[i], stop),
                             daemon=True)
        threads.append(t)
    t0 = time.time()
    for t in threads: t.start()
    for t in threads: t.join()
    wall = time.time() - t0
    stop_background(bg_stops, bg_threads)
    per_stream = []
    for i in range(n):
        sap = per_stream_sap(splits[i], results[i])
        per_stream.append({
            "stream_id": i, "sid": sids[i], "device": placement[i],
            "sap": round(sap["sap_5095"], 5),
            "sap_s": round(sap["sap_small"], 5), "sap_m": round(sap["sap_medium"], 5),
            "sap_l": round(sap["sap_large"], 5),
            "skip": round(sap["frame_skip_pct"], 2),
            "eff_mean_ms": round(sap["eff_mean_ms"], 3),
            "infer_mean_ms": round(sap["infer_mean_ms"], 3),
        })
    saps = [s["sap"] for s in per_stream]
    return {"n_streams": n, "mean_sap": float(np.mean(saps)), "worst_sap": float(np.min(saps)),
            "median_sap": float(np.median(saps)), "p10_sap": float(np.percentile(saps, 10)),
            "per_stream": per_stream, "wall_sec": wall}


def summarize(agg, placement):
    ps = agg["per_stream"]
    gpu = [s for s in ps if s["device"] == "GPU"]
    npu = [s for s in ps if s["device"] == "NPU"]
    size_src = gpu if gpu else npu            # per-size from the contention-bearing device
    gskip = [s["skip"] for s in gpu]; nskip = [s["skip"] for s in npu]
    margin_src = gpu if gpu else npu
    return {
        "gpu_skip_pct": round(float(np.mean(gskip)), 2) if gskip else 0.0,
        "npu_skip_pct": round(float(np.mean(nskip)), 2) if nskip else 0.0,
        "worst_sap": round(agg["worst_sap"], 5), "mean_sap": round(agg["mean_sap"], 5),
        "median_sap": round(agg["median_sap"], 5), "p10_sap": round(agg["p10_sap"], 5),
        "sap_small": round(float(np.mean([s["sap_s"] for s in size_src])), 5),
        "sap_medium": round(float(np.mean([s["sap_m"] for s in size_src])), 5),
        "sap_large": round(float(np.mean([s["sap_l"] for s in size_src])), 5),
        "deadline_margin_ms_mean": round(float(np.mean([s["eff_mean_ms"] - PERIOD for s in margin_src])), 3),
    }


def run_cell(run_id, group, N, placement, k, rep, sids, splits, gpu_models, npu_models, m):
    key = f"{group}/N{N}/{pstr(placement)}/k{k}/rep{rep}"
    if m["done"].get(key):
        print(f"  [skip cached] {key}", flush=True); return
    bg = reg_level(k)
    ng = sum(1 for d in placement if d == "GPU"); nn = sum(1 for d in placement if d == "NPU")
    torch.set_num_threads(THREADS)
    t0 = time.time()
    agg = measure_multistream_full(sids, splits, placement, gpu_models[:ng], npu_models[:nn], bg)
    t1 = time.time()
    s = summarize(agg, placement)
    row = {"run_id": run_id, "group": group, "N": N, "placement": pstr(placement), "k": k, "rep": rep,
           "t_start": round(t0, 3), "t_end": round(t1, 3),
           "per_stream_json": json.dumps(agg["per_stream"]),
           "period_ms": round(PERIOD, 3), "fps": FPS, "detector": "yolo11s", "dataset": DATASET,
           "timestamp": int(t1)}
    row.update(s)
    app(RAW, RAW_COLS, row)
    m["done"][key] = {"ts": int(time.time())}; save(m)
    print(f"  {key}: gpu_skip={s['gpu_skip_pct']} worst={s['worst_sap']} "
          f"s/m/l={s['sap_small']}/{s['sap_medium']}/{s['sap_large']} "
          f"margin={s['deadline_margin_ms_mean']}ms ({t1-t0:.1f}s)", flush=True)
    return agg


def start_sampler():
    out = RES / "util_samples.csv"
    p = subprocess.Popen(["taskset", "-c", SAMPLER_CORE,
                          str(SCRIPT_DIR.parent.parent / ".venv/bin/python"),
                          str(SCRIPT_DIR / "gpu_util_sampler.py"), str(out), str(SAMPLE_INTERVAL)])
    time.sleep(2.0)
    return p

def stop_sampler(p):
    if p is None: return
    p.send_signal(signal.SIGTERM)
    try: p.wait(timeout=5)
    except Exception: p.kill()


def matrix_summary():
    n4 = sum(REPS_N4[k] * 5 for k in KS)
    n2g = sum(REPS_HOMO_GPU[k] for k in KS)
    n8g = sum(REPS_HOMO_GPU[k] for k in KS)
    n2n = len(NPU_KS) * REPS_NPU
    n8n = len(NPU_KS) * REPS_NPU
    tot = n4 + n2g + n8g + n2n + n8n
    print("=== rev30 measurement matrix ===", flush=True)
    print(f"  NPU mode = {NPU_MODE!r}  deadline = {PERIOD:.3f} ms  threads={THREADS}", flush=True)
    print(f"  N4 5-ratio (GGGG/NGGG/NNGG/NNNG/NNNN), reps/k={REPS_N4}: {n4} calls", flush=True)
    print(f"  N2 All-GPU 3/k: {n2g} ; N8 All-GPU 3/k: {n8g}", flush=True)
    print(f"  N2 All-NPU k{NPU_KS}x{REPS_NPU}: {n2n} ; N8 All-NPU: {n8n}", flush=True)
    print(f"  TOTAL measure calls = {tot}", flush=True)
    return tot


def equivalence_check(sids, splits, gpu_models, npu_models):
    """Assert measure_multistream_full == stock measure_multistream on k=0 N=4 All-GPU."""
    bg = reg_level(0); pl = ["GPU"] * 4
    a = measure_multistream_full(sids, splits, pl, gpu_models[:4], npu_models[:0], bg)
    b = measure_multistream(sids, splits, pl, gpu_models[:4], npu_models[:0], bg)
    al = float(np.mean([s["sap_l"] for s in a["per_stream"]]))
    bl = float(np.mean([s["sap_l"] for s in b["per_stream"]]))
    dw = abs(a["worst_sap"] - b["worst_sap"]); dm = abs(a["mean_sap"] - b["mean_sap"]); dl = abs(al - bl)
    ok = dw < 0.005 and dm < 0.005 and dl < 0.005
    print(f"  EQUIV full-vs-stock k0 N4: worst {a['worst_sap']:.4f}/{b['worst_sap']:.4f} (Δ{dw:.4f}) "
          f"mean {a['mean_sap']:.4f}/{b['mean_sap']:.4f} (Δ{dm:.4f}) "
          f"sap_l {al:.4f}/{bl:.4f} (Δ{dl:.4f}) -> {'OK' if ok else 'MISMATCH'}", flush=True)
    return ok


def main():
    torch.set_num_threads(THREADS)
    run_id = f"rev30_{int(time.time())}"
    m = man()
    preload_background_models(max_level="L1")     # resnet50 lever only
    val = load_val()

    # ---------------- N=2 high-k EXTENSION (Fig3a N=2 crossover) ----------------
    if EXT_N2KS:
        print(f"--- EXT: N=2 All-GPU at k={EXT_N2KS} (3 reps, no sampler), append to {RAW.name} ---", flush=True)
        gpu_models = [FGModelGPUGeneric(DET["ultralytics_pt"]) for _ in range(2)]
        sp2 = [load_split_for_sid(val, s) for s in PANEL2]
        for k in EXT_N2KS:
            for rep in range(REPS_NPU):           # 3 reps
                run_cell(run_id, "N2", 2, ["GPU"] * 2, k, rep, PANEL2, sp2, gpu_models, [], m)
        print("=== rev30 N=2 extension done ===", flush=True)
        return

    tot = matrix_summary()
    n_models = 4 if SMOKE else 8
    gpu_models = [FGModelGPUGeneric(DET["ultralytics_pt"]) for _ in range(n_models)]
    npu_models = load_npu_engines(DET, DET["multistream_mxq"], NPU_MODE, n_models)
    set_active_npu_engines(npu_models)

    sp4 = [load_split_for_sid(val, s) for s in PANEL4]
    sp2 = [load_split_for_sid(val, s) for s in PANEL2]
    sp8 = [load_split_for_sid(val, s) for s in PANEL8]

    if SMOKE:
        print("\n--- SMOKE: equivalence + schema check (k0,k1 N4, 1 rep) ---", flush=True)
        if not equivalence_check(PANEL4, sp4, gpu_models, npu_models):
            print("  !! EQUIV MISMATCH — aborting smoke.", flush=True); return
        for k in [0, 1]:
            for r in range(5):
                run_cell(run_id, "N4", 4, placement_for_ratio(r), k, 0,
                         PANEL4, sp4, gpu_models, npu_models, m)
        print("--- smoke done; inspect rev30_raw_smoke.csv ---", flush=True)
        dispose_npu_for("yolo11s"); return

    # ---------------- FULL RUN ----------------
    print(f"\n--- FULL RUN ({tot} calls), sampler ON ---", flush=True)
    samp = start_sampler()
    try:
        # N=4 5-ratio atomic sweep (Fig3a-N4 + Fig3b + Fig2 + tab:main)
        for k in KS:
            for rep in range(REPS_N4[k]):
                for r in range(5):
                    run_cell(run_id, "N4", 4, placement_for_ratio(r), k, rep,
                             PANEL4, sp4, gpu_models, npu_models, m)
        # N=2 / N=8 All-GPU (Fig3a curves)
        for k in KS:
            for rep in range(REPS_HOMO_GPU[k]):
                run_cell(run_id, "N2", 2, ["GPU"] * 2, k, rep, PANEL2, sp2, gpu_models, npu_models, m)
            for rep in range(REPS_HOMO_GPU[k]):
                run_cell(run_id, "N8", 8, ["GPU"] * 8, k, rep, PANEL8, sp8, gpu_models, npu_models, m)
        # N=2 / N=8 All-NPU (flat reference)
        for k in NPU_KS:
            for rep in range(REPS_NPU):
                run_cell(run_id, "N2", 2, ["NPU"] * 2, k, rep, PANEL2, sp2, gpu_models, npu_models, m)
            for rep in range(REPS_NPU):
                run_cell(run_id, "N8", 8, ["NPU"] * 8, k, rep, PANEL8, sp8, gpu_models, npu_models, m)
    finally:
        stop_sampler(samp)
    dispose_npu_for("yolo11s")
    print("=== rev30 full run done ===", flush=True)


if __name__ == "__main__":
    main()
