"""Step M — TASK D: Worst-stream gain across detectors (YOLOv11s row).

Per claude_code_experiments.md TASK D:
  worst gain        = SizeAware_worst_sAP - SizeBlindRev_worst_sAP
  mean gain         = SizeAware_mean_sAP  - SizeBlindRev_mean_sAP
  worst/mean ratio  = worst gain / mean gain
  inverts?          = (worst gain > 0)

This aggregator reuses Step G2 (step_g2_single_mode.csv) for Composition A
(size-diversity-maximizing, 4 small-rich + 4 large-rich logs) at N=4 and N=8
under bg L1_light.

Per the user's Q1(c) and Q2(b): only YOLOv11s row is populated; YOLOv11n,
YOLOv11m, and RT-DETR rows remain TBD (Mobilint INT8 mxq not available).

Outputs:
  results/gen_gain.csv               per-N/per-bg row + final aggregated row
  paper/tables/gen_gain.tex          tab:gen-gain scaffold (s row filled)
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

SCRIPT_DIR = Path(__file__).resolve().parent
RES = SCRIPT_DIR.parent / "results"
OUT_CSV = RES / "gen_gain.csv"
OUT_TEX = SCRIPT_DIR.parent.parent / "paper" / "tables" / "gen_gain.tex"

DETECTOR = "YOLOv11s"


def _resolve_row(df, n_streams, bg, name_prefix, must_match_spec=None):
    sub = df[(df.n_streams == n_streams) & (df.bg_level == bg) &
             (df.placement_name.str.startswith(name_prefix))]
    if must_match_spec is not None:
        sub = sub[sub.placement_spec == must_match_spec]
    if not len(sub):
        return None
    return sub.iloc[0]


def main():
    df = pd.read_csv(RES / "step_g2_single_mode.csv")

    cells = []
    # ---- N=4, bg L1 (= L1_light) ----
    # Composition A N=4 (sids [2, 22, 3, 21] in step_g2 — Step G2's COMP[4] = ([2,22], [3,21]))
    # SizeAware places small (sids 2, 22) on NPU; SizeBlindRev places large (3, 21) on NPU.
    sa = _resolve_row(df, 4, "L1", "SizeAware",
                       must_match_spec='["NPU", "NPU", "GPU", "GPU"]')
    sb = _resolve_row(df, 4, "L1", "SizeBlindRev",
                       must_match_spec='["GPU", "GPU", "NPU", "NPU"]')
    cells.append(("N=4", "L1_light", sa, sb))

    # ---- N=8, bg L1 (= L1_light) ----
    # SizeAware_NPU4 spec = small-rich → NPU (4 NPU + 4 GPU)
    sa8 = _resolve_row(df, 8, "L1", "SizeAware_NPU4",
                       must_match_spec='["NPU", "NPU", "NPU", "NPU", "GPU", "GPU", "GPU", "GPU"]')
    sb8 = _resolve_row(df, 8, "L1", "SizeBlindRev",
                       must_match_spec='["GPU", "GPU", "GPU", "GPU", "NPU", "NPU", "NPU", "NPU"]')
    cells.append(("N=8", "L1_light", sa8, sb8))

    rows = []
    for tag, bg, sa, sb in cells:
        if sa is None or sb is None:
            print(f"[stepM] {tag} {bg}: missing row(s); skipping")
            continue
        worst_gain = float(sa["worst_sap"]) - float(sb["worst_sap"])
        mean_gain = float(sa["mean_sap"]) - float(sb["mean_sap"])
        ratio = worst_gain / mean_gain if abs(mean_gain) > 1e-9 else float("inf")
        rows.append({
            "detector": DETECTOR, "cell": tag, "bg": bg,
            "sa_worst": round(float(sa["worst_sap"]), 4),
            "sb_worst": round(float(sb["worst_sap"]), 4),
            "sa_mean": round(float(sa["mean_sap"]), 4),
            "sb_mean": round(float(sb["mean_sap"]), 4),
            "worst_gain": round(worst_gain, 4),
            "mean_gain": round(mean_gain, 4),
            "worst_mean_ratio": round(ratio, 2),
            "inverts": (worst_gain > 0),
        })
        print(f"[stepM] {tag} {bg}: SA worst={sa['worst_sap']:.4f}  "
              f"SBR worst={sb['worst_sap']:.4f}  worst_gain={worst_gain:+.4f}  "
              f"mean_gain={mean_gain:+.4f}  ratio={ratio:.2f}x  inverts={worst_gain>0}")

    # Aggregated row for the gen-gain table (use N=4 L1_light as primary —
    # the inversion sweet spot used by the paper).
    primary = next((r for r in rows if r["cell"] == "N=4"), rows[0])
    rows.append({
        "detector": DETECTOR, "cell": "PRIMARY", "bg": primary["bg"],
        "sa_worst": primary["sa_worst"], "sb_worst": primary["sb_worst"],
        "sa_mean":  primary["sa_mean"],  "sb_mean":  primary["sb_mean"],
        "worst_gain": primary["worst_gain"],
        "mean_gain":  primary["mean_gain"],
        "worst_mean_ratio": primary["worst_mean_ratio"],
        "inverts": primary["inverts"],
    })
    pd.DataFrame(rows).to_csv(OUT_CSV, index=False)
    print(f"\nsaved {OUT_CSV}")

    # ---- LaTeX (tab:gen-gain) ----
    OUT_TEX.parent.mkdir(parents=True, exist_ok=True)
    p = primary
    inv = "yes" if p["inverts"] else "no"
    with open(OUT_TEX, "w") as f:
        f.write("% Auto-generated by accv_experiments/scripts/step_m_gen_gain.py\n")
        f.write("% Worst-stream gain SizeAware - SizeBlindRev on Composition A\n")
        f.write("% (4 small-rich + 4 large-rich), N=4 bg L1_light.\n")
        f.write("% YOLOv11n/m and RT-DETR rows TBD: no Mobilint INT8 mxq available.\n")
        f.write("\\begin{tabular}{ll|ccc}\n\\toprule\n")
        f.write("Detector & family & inverts? & worst gain & worst/mean ratio \\\\\n")
        f.write("\\midrule\n")
        f.write("YOLOv11n  & YOLO    & TBD & TBD & TBD \\\\\n")
        f.write(f"YOLOv11s  & YOLO    & {inv} & "
                f"${p['worst_gain']:+.3f}$ & "
                f"${p['worst_mean_ratio']:.1f}\\times$ \\\\\n")
        f.write("YOLOv11m  & YOLO    & TBD & TBD & TBD \\\\\n")
        f.write("RT-DETR-? & DETR    & TBD & TBD & TBD \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")
    print(f"saved {OUT_TEX}")


if __name__ == "__main__":
    main()
