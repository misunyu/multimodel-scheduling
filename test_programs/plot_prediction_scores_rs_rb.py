#!/usr/bin/env python3
"""
Plot combination scores across parameter token groups from prediction test result files.

- Scans a directory for files including tokens like rs_XX, rb_YY, yb_ZZ, ys_WW (order-insensitive),
  where values are in {10,20,...,100}.
- Supports JSON and YAML result files generated by the suite.
- Groups by one of the following key modes selected via --key:
  * rs-rb
  * rs-rb-yb
  * rs-rb-yb-ys
- For each discovered key, extracts per-combination scores from the file's 'data' list and plots them.
- Saves the figure as a PDF in the same directory (scores_by_<key>.pdf by default).

Usage:
  python test_programs/plot_prediction_scores_rs_rb.py [--dir <results_dir>] [--out <pdf_path>] [--key <mode>]

Examples:
  python test_programs/plot_prediction_scores_rs_rb.py --key rs-rb
  python test_programs/plot_prediction_scores_rs_rb.py --key rs-rb-yb
  python test_programs/plot_prediction_scores_rs_rb.py --key rs-rb-yb-ys --out my_plot.pdf
"""
from __future__ import annotations

import argparse
import json
import re
from collections import defaultdict
from pathlib import Path
from typing import Dict, List, Tuple, Any

# Use a non-interactive backend
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

try:
    import yaml  # type: ignore
except Exception:  # pragma: no cover - optional dependency (but included in this repo's requirements)
    yaml = None


PAIR_VALUES = list(range(10, 101, 10))  # 10, 20, ..., 100

# Regex to capture token values regardless of order, allowing extra tokens
# Example filenames:
#   predict_performance_..._rs_20_rb_30.yaml
#   predict_performance_..._rb_20_rs_20_yb_30.json
#   predict_performance_..._rs_20_rb_20_yb_30_ys_40.json
RS_PATTERN = re.compile(r"(?:^|[_-])rs_(\d+)(?:[_-]|\.)")
RB_PATTERN = re.compile(r"(?:^|[_-])rb_(\d+)(?:[_-]|\.)")
YB_PATTERN = re.compile(r"(?:^|[_-])yb_(\d+)(?:[_-]|\.)")
YS_PATTERN = re.compile(r"(?:^|[_-])ys_(\d+)(?:[_-]|\.)")


def _extract_tokens_from_name(name: str) -> Dict[str, int]:
    """Extract rs, rb, yb, ys integers from filename (if present and valid)."""
    out: Dict[str, int] = {}

    def _grab(pat: re.Pattern[str], key: str) -> None:
        m = pat.search(name)
        if not m:
            return
        try:
            v = int(m.group(1))
            if v in PAIR_VALUES:
                out[key] = v
        except Exception:
            pass

    _grab(RS_PATTERN, 'rs')
    _grab(RB_PATTERN, 'rb')
    _grab(YB_PATTERN, 'yb')
    _grab(YS_PATTERN, 'ys')
    return out


def _load_result_file(path: Path) -> Dict[str, Any] | None:
    try:
        if path.suffix.lower() in {'.json'}:
            return json.loads(path.read_text(encoding='utf-8'))
        elif path.suffix.lower() in {'.yaml', '.yml'}:
            if yaml is None:
                raise RuntimeError("PyYAML is not available to read YAML files.")
            return yaml.safe_load(path.read_text(encoding='utf-8'))
        else:
            return None
    except Exception as e:
        print(f"[WARN] Failed to read '{path}': {e}")
        return None


def collect_scores(result_dir: Path, key_mode: str) -> Dict[Tuple[int, ...], List[Tuple[str, float, bool]]]:
    """Return mapping keyed by selected mode to list of (combination, score, is_best).

    key_mode in {'rs-rb', 'rs-rb-yb', 'rs-rb-yb-ys'}
    """
    scores: Dict[Tuple[int, ...], List[Tuple[str, float, bool]]] = defaultdict(list)

    if not result_dir.exists():
        print(f"[WARN] Result directory does not exist: {result_dir}")
        return scores

    for path in sorted(result_dir.iterdir()):
        if not path.is_file():
            continue
        if path.suffix.lower() not in {'.json', '.yaml', '.yml'}:
            continue

        toks = _extract_tokens_from_name(path.name)
        if key_mode == 'rs-rb':
            required = ('rs', 'rb')
            key = (toks.get('rs'), toks.get('rb'))
        elif key_mode == 'rs-rb-yb':
            required = ('rs', 'rb', 'yb')
            key = (toks.get('rs'), toks.get('rb'), toks.get('yb'))
        elif key_mode == 'rs-rb-yb-ys':
            required = ('rs', 'rb', 'yb', 'ys')
            key = (toks.get('rs'), toks.get('rb'), toks.get('yb'), toks.get('ys'))
        else:
            continue

        # Skip if any required token missing
        if any(v is None for v in key):
            continue

        data = _load_result_file(path)
        if not isinstance(data, dict):
            continue
        items = data.get('data')
        if not isinstance(items, list):
            continue

        # Detect best deployment name if present
        best_combo = data.get('best deployment')

        for item in items:
            try:
                combo = item.get('combination')
                score = item.get('score')
                if combo is None or score is None:
                    continue
                score_f = float(score)
                is_best = (str(combo) == str(best_combo)) if best_combo is not None else False
                scores[key].append((str(combo), score_f, is_best))
            except Exception:
                continue

    # Enforce exactly one best deployment per x-axis key (tuple)
    # If none or multiple are flagged, pick the highest score as best for that key
    try:
        for k, lst in list(scores.items()):
            if not lst:
                continue
            best_count = sum(1 for _c, s, is_b in lst if is_b)
            if best_count != 1:
                # Select the one with the highest score
                max_idx = max(range(len(lst)), key=lambda i: lst[i][1])
                new_lst: List[Tuple[str, float, bool]] = []
                for i, (cname, sc, is_b) in enumerate(lst):
                    new_lst.append((cname, sc, i == max_idx))
                scores[k] = new_lst
                # Warn the user for transparency
                print(f"[INFO] Adjusted best deployment for key {k}: had {best_count}, set index {max_idx} (max score) as best.")
    except Exception:
        # Do not fail plotting due to consistency step
        pass

    return scores


def plot_scores(scores_by_key: Dict[Tuple[int, ...], List[Tuple[str, float, bool]]], out_pdf: Path, key_mode: str) -> None:
    # Order by discovered keys ascending
    ordered_keys: List[Tuple[int, ...]] = sorted(scores_by_key.keys())
    if not ordered_keys:
        print(f"[INFO] No matching {key_mode} result files found to plot.")
        return

    # Prepare x positions
    def _label(t: Tuple[int, ...]) -> str:
        return '(' + ','.join(str(x) for x in t) + ')'

    x_labels = [_label(t) for t in ordered_keys]
    x_positions = list(range(len(ordered_keys)))

    # Collect points
    xs: List[int] = []
    ys: List[float] = []
    base_colors: List[str] = []
    is_best_flags: List[bool] = []
    palette = ['C0', 'C1', 'C2', 'C3', 'C4', 'C5', 'C6', 'C7', 'C8', 'C9']

    for idx, key in enumerate(ordered_keys):
        entries = scores_by_key.get(key, [])
        for _j, (_combo, score, is_best) in enumerate(entries):
            xs.append(idx)
            ys.append(score)
            base_colors.append(palette[idx % len(palette)])
            is_best_flags.append(bool(is_best))

    # Compute density-based alpha so overlapping points appear darker
    # Bin y to reduce floating noise and consider near-overlaps as the same bin
    y_bin_size = 0.1
    counts = {}
    yb_list = []
    for x, y in zip(xs, ys):
        yb = round(y / y_bin_size) * y_bin_size
        yb_list.append(yb)
        key_bin = (x, yb)
        counts[key_bin] = counts.get(key_bin, 0) + 1

    max_count = max(counts.values()) if counts else 1
    alpha_min, alpha_max = 0.15, 0.95

    rgba_colors = []
    for base, x, yb in zip(base_colors, xs, yb_list):
        c = counts.get((x, yb), 1)
        if max_count > 1:
            alpha = alpha_min + (alpha_max - alpha_min) * (c - 1) / (max_count - 1)
        else:
            alpha = alpha_min
        rgba = matplotlib.colors.to_rgba(base, alpha=alpha)
        rgba_colors.append(rgba)

    # Split into normal vs best for different markers
    x_norm: List[int] = []
    y_norm: List[float] = []
    c_norm: List[Any] = []
    x_best: List[int] = []
    y_best: List[float] = []
    c_best: List[Any] = []
    for x, y, c, is_b in zip(xs, ys, rgba_colors, is_best_flags):
        if is_b:
            x_best.append(x)
            y_best.append(y)
            c_best.append(c)
        else:
            x_norm.append(x)
            y_norm.append(y)
            c_norm.append(c)

    # Set font to match LaTeX appearance (Times New Roman)
    plt.rcParams['font.family'] = 'serif'
    plt.rcParams['font.serif'] = ['Times New Roman'] + plt.rcParams['font.serif']

    plt.figure(figsize=(max(10, len(ordered_keys) * 0.8), 6))
    if x_norm:
        plt.scatter(x_norm, y_norm, c=c_norm, s=16, marker='o', edgecolors='none')
    if x_best:
        plt.scatter(x_best, y_best, c=c_best, s=64, marker='*', edgecolors='k', linewidths=0.4, label='best deployment')
    plt.xticks(ticks=x_positions, labels=x_labels, rotation=90, fontsize=12)
    plt.yticks(fontsize=12)
    plt.xlabel(f'{key_mode} keys', fontsize=14)
    plt.ylabel('score', fontsize=14)
    # plt.title(f'Combination scores per {key_mode} key', fontsize=16)
    if x_best:
        plt.legend(loc='best', fontsize=12)
    plt.grid(True, axis='y', linestyle='--', alpha=0.3)
    plt.tight_layout()

    out_pdf.parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(out_pdf, format='pdf')
    plt.close()
    print(f"[OK] Saved plot to: {out_pdf}")


def main():
    parser = argparse.ArgumentParser(description='Plot combination scores across selected parameter key groups.')
    parser.add_argument('--dir', dest='result_dir', default='./xgboost_model/performance_data/prediction_test_results',
                        help='Directory containing prediction test result files (json/yaml).')
    parser.add_argument('--out', dest='out_pdf', default=None,
                        help='Output PDF path. The output filename will be prefixed with the result folder name.\n                             If not provided, saves to <result_dir>/<result_dir_name>_scores_by_<key>.pdf')
    parser.add_argument('--key', dest='key_mode', default='rs-rb', choices=['rs-rb', 'rs-rb-yb', 'rs-rb-yb-ys'],
                        help='Key grouping mode: rs-rb | rs-rb-yb | rs-rb-yb-ys')
    args = parser.parse_args()

    result_dir = Path(args.result_dir)
    if args.out_pdf:
        # Respect the provided path's directory, but prefix the filename with the result folder name
        provided = Path(args.out_pdf)
        parent = provided.parent if str(provided.parent) not in {"", "."} else result_dir
        fname = provided.name
        prefix = f"{result_dir.name}_"
        if not fname.startswith(prefix):
            fname = prefix + fname
        out_pdf = parent / fname
    else:
        default_name = f"{result_dir.name}_scores_by_{args.key_mode.replace('-', '_')}.pdf"
        out_pdf = result_dir / default_name

    scores_by_key = collect_scores(result_dir, args.key_mode)
    plot_scores(scores_by_key, out_pdf, args.key_mode)


if __name__ == '__main__':
    main()
