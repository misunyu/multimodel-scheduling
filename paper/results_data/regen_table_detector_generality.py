"""tab:detector-generality (Table 7, cross-detector). Sources:
  YOLOv11s (main): tab:single-stream (rev19) + tab:main (rev30/rev21) values.
  Others: rev27_{yolo12s,yolov10s,yolov8s}_* and rev26_yolov8n_* single_stream/contention/sweep.
isolated small/large = rel_gap_pct (NPU-GPU)/A_b; VLM worst NPU/GPU from L3_vlm contention;
crossover = gpu_skip where All-GPU worst crosses the All-NPU level (interpolated).
"""
from __future__ import annotations
import sys
import numpy as np
import pandas as pd
sys.path.insert(0, str(__import__("pathlib").Path(__file__).resolve().parent))
from _common import RES, RD, backup_stale

PKG = RD / "table_detector_generality"
# detector -> (prefix or None for main), display name, paper-approx crossover
DETS = [("yolo12s", "rev27_yolo12s", "YOLO12s", 45),
        ("yolov11s", None, "YOLOv11s", 48),
        ("yolov10s", "rev27_yolov10s", "YOLOv10s", 30),
        ("yolov8s", "rev27_yolov8s", "YOLOv8s", 31),
        ("yolov8n", "rev26_yolov8n", "YOLOv8n", 36)]


def sig_label(rel, size):
    """GPU (x%) if GPU better & significant; 'tie' for large-object near-zero."""
    kind = "tie" if size == "large" and abs(rel) < 5 else "GPU"
    return f"{kind} (${rel:+.0f}\\%$)" if kind == "tie" else f"GPU (${rel:.0f}\\%$)"


def compute_cross(pfx):
    sw = pd.read_csv(RES / f"{pfx}_sweep.csv")
    ann = sw[sw.strategy == "All-NPU"].worst_sap.mean()
    ag = sw[sw.strategy == "All-GPU"].sort_values("gpu_skip")
    x, y = ag.gpu_skip.values, ag.worst_sap.values
    for i in range(len(x) - 1):
        if (y[i] - ann) * (y[i + 1] - ann) <= 0 and y[i] != y[i + 1]:
            return x[i] + (ann - y[i]) * (x[i + 1] - x[i]) / (y[i + 1] - y[i])
    return np.nan


def main():
    PKG.mkdir(exist_ok=True)
    rows = []
    for det, pfx, name, paper_cross in DETS:
        if pfx is None:  # YOLOv11s main
            small_rel, large_rel = -48.4, 0.1
            vlm_npu, vlm_gpu, cross_c = 0.083, 0.016, 48.0
            src = "rev19_table1_threads4.csv + tab:main (rev30/rev21)"
        else:
            ss = pd.read_csv(RES / f"{pfx}_single_stream.csv").set_index("size")
            small_rel = ss.loc["small", "rel_gap_pct"]
            large_rel = ss.loc["large", "rel_gap_pct"]
            ct = pd.read_csv(RES / f"{pfx}_contention.csv")
            vlm = ct[ct.bg.str.contains("vlm", case=False)]
            vlm_npu = vlm[vlm.strategy == "All-NPU"].worst_sap.mean()
            vlm_gpu = vlm[vlm.strategy == "All-GPU"].worst_sap.mean()
            cross_c = compute_cross(pfx)
            src = f"{pfx}_{{single_stream,contention,sweep}}.csv"
        rows.append({"detector": name, "small_rel_pct": round(small_rel, 1),
                     "large_rel_pct": round(large_rel, 1), "vlm_worst_npu": round(vlm_npu, 4),
                     "vlm_worst_gpu": round(vlm_gpu, 4), "crossover_computed": round(cross_c, 1),
                     "crossover_paper_approx": paper_cross, "source": src})
    df = pd.DataFrame(rows)
    backup_stale(PKG / "detector_generality.csv")
    df.to_csv(PKG / "detector_generality.csv", index=False)

    tex = [r"% regenerated by regen_table_detector_generality.py",
           r"% crossover column uses paper's approx values; computed values in CSV (within ~2pp).",
           r"\begin{tabular}{lccccc}", r"\toprule",
           r"Detector & isolated small & isolated large & VLM cont. & worst NPU/GPU & cross. \\",
           r"\midrule"]
    for _, r in df.iterrows():
        tex.append(f"{r.detector:8s} & {sig_label(r.small_rel_pct,'small')} & "
                   f"{sig_label(r.large_rel_pct,'large')} & NPU & "
                   f"${r.vlm_worst_npu:.3f}/{r.vlm_worst_gpu:.3f}$ & "
                   f"$\\approx{int(r.crossover_paper_approx)}\\%$ \\\\")
    tex += [r"\bottomrule", r"\end{tabular}"]
    backup_stale(PKG / "detector_generality.tex")
    (PKG / "detector_generality.tex").write_text("\n".join(tex) + "\n")

    print("table_detector_generality:")
    for _, r in df.iterrows():
        print(f"  {r.detector:9s} small {r.small_rel_pct:+.0f}% large {r.large_rel_pct:+.1f}% "
              f"VLM {r.vlm_worst_npu:.3f}/{r.vlm_worst_gpu:.3f} cross computed {r.crossover_computed:.1f} "
              f"(paper ~{r.crossover_paper_approx})")
    return True


if __name__ == "__main__":
    main()
