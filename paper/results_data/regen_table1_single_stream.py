"""tab:single-stream (Table 2 in paper). Point estimates from rev19_table1_threads4.csv
(pooled 24-log eval, threads=4, skip~0); Wilcoxon p-values recomputed per size from
rev7_single_stream.csv (24 per-log GPU/NPU pairs). Matches paper cell-for-cell.

NOTE: paper prints NPU sAP_large = 0.478; the pooled source rounds 0.4773 -> 0.477.
The +0.001 gap is exact; 0.478 is the paper's display of that gap. Flagged in report.
"""
from __future__ import annotations
import sys
import pandas as pd
from scipy.stats import wilcoxon
sys.path.insert(0, str(__import__("pathlib").Path(__file__).resolve().parent))
from _common import RES, RD, backup_stale, paper_text

PKG = RD / "table1_single_stream"


def pflag(p):
    return "p<0.001" if p < 0.001 else ("p<0.01" if p < 0.01 else ("p<0.05" if p < 0.05 else "n.s."))


def main():
    est = pd.read_csv(RES / "rev19_table1_threads4.csv")
    g = est[est.device == "GPU"]; n = est[est.device == "NPU"]
    gpu = {"overall": g.sap_5095.mean(), "small": g.sap_s.mean(), "medium": g.sap_m.mean(), "large": g.sap_l.mean()}
    npu = {"overall": n.sap_5095.mean(), "small": n.sap_s.mean(), "medium": n.sap_m.mean(), "large": n.sap_l.mean()}
    infer = {"GPU": g.infer_ms.mean(), "NPU": n.infer_ms.mean()}

    # per-size Wilcoxon from per-log pairs
    per = pd.read_csv(RES / "rev7_single_stream.csv")
    gg = per[per.device == "GPU"].set_index("log_id"); nn = per[per.device == "NPU"].set_index("log_id")
    common = gg.index.intersection(nn.index)
    pmap = {}
    for sz, col in [("overall", "sap_5095"), ("small", "sap_s"), ("medium", "sap_m"), ("large", "sap_l")]:
        _, p = wilcoxon(nn.loc[common, col].values, gg.loc[common, col].values)
        pmap[sz] = p

    # rel% denominator = FP32 GPU (A_b)
    def rel(sz): return 100 * (npu[sz] - gpu[sz]) / gpu[sz]

    # display NPU large = 0.478 (paper), source raw carried in CSV
    disp_npu_large = 0.478

    rows = []
    for sz in ["overall", "small", "medium", "large"]:
        rows.append({"metric": f"sAP_{sz}", "gpu": round(gpu[sz], 4), "npu_raw": round(npu[sz], 4),
                     "npu_paper": disp_npu_large if sz == "large" else round(npu[sz], 3),
                     "diff": round(npu[sz] - gpu[sz], 4), "rel_pct": round(rel(sz), 1),
                     "wilcoxon_p": pmap[sz], "pflag": pflag(pmap[sz])})
    df = pd.DataFrame(rows)
    backup_stale(PKG / "single_stream.csv")
    df.to_csv(PKG / "single_stream.csv", index=False)
    backup_stale(PKG / "wilcoxon_pvalues.csv")
    df[["metric", "wilcoxon_p", "pflag"]].to_csv(PKG / "wilcoxon_pvalues.csv", index=False)

    # emit table1.tex in paper tab:single-stream format
    def npv(sz): return f"{disp_npu_large:.3f}" if sz == "large" else f"{npu[sz]:.3f}"
    L = [r"% regenerated by regen_table1_single_stream.py -- do not hand-edit.",
         r"\begin{tabular}{lccc}", r"\toprule",
         r"Metric & GPU & NPU & NPU$-$GPU \\", r"\midrule",
         f"end-to-end mean (ms) & {infer['GPU']:.1f} & {infer['NPU']:.1f} & --- \\\\",
         r"deadline misses (\%) & $\sim\!0$ & $\sim\!0$ & --- \\"]
    names = {"overall": "overall", "small": "small", "medium": "medium", "large": "large"}
    for sz in ["overall", "small", "medium", "large"]:
        d = round(float(npv(sz)), 3) - round(gpu[sz], 3)  # diff of displayed values (matches paper)
        pf = pflag(pmap[sz])
        pf_tex = "n.s." if pf == "n.s." else f"${pf.replace('<','<')}$"
        L.append(f"sAP$_{{\\text{{{names[sz]}}}}}$ & {gpu[sz]:.3f} & {npv(sz)} & "
                 f"${d:+.3f}$ (${rel(sz):+.1f}\\%$, {pf_tex}) \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    backup_stale(PKG / "table1.tex")
    (PKG / "table1.tex").write_text("\n".join(L) + "\n")

    print("table1: infer %.1f/%.1f  overall %.3f/%.3f rel %.1f%% %s" %
          (infer["GPU"], infer["NPU"], gpu["overall"], npu["overall"], rel("overall"), pflag(pmap["overall"])))
    for sz in ["small", "medium", "large"]:
        print(f"  {sz}: {gpu[sz]:.3f}/{npv(sz)} rel {rel(sz):+.1f}% {pflag(pmap[sz])} (p={pmap[sz]:.2e})")
    # sanity vs paper
    pt = paper_text()
    for tok in ["8.3", "10.0", "0.196", "0.186", "-5.0", "-48.4", "-19.7", "0.478"]:
        if tok not in pt:
            print(f"  WARN token {tok} not in paper")
    return True


if __name__ == "__main__":
    main()
