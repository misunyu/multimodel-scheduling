"""tab:metric-sensitivity (Table 6). Source rev28_metric_sensitivity.csv."""
from __future__ import annotations
import sys
import pandas as pd
sys.path.insert(0, str(__import__("pathlib").Path(__file__).resolve().parent))
from _common import RES, RD, backup_stale

PKG = RD / "table_metric_sensitivity"
LBL = {"mean": "mean", "median": "median", "p10": r"$p_{10}$", "worst": "worst"}


def main():
    d = pd.read_csv(RES / "rev28_metric_sensitivity.csv")
    PKG.mkdir(exist_ok=True)
    backup_stale(PKG / "metric_sensitivity.csv")
    d.to_csv(PKG / "metric_sensitivity.csv", index=False)
    tex = [r"% regenerated by regen_table_metric_sensitivity.py from rev28_metric_sensitivity.csv",
           r"\begin{tabular}{lccc}", r"\toprule",
           r"statistic & All-GPU & All-NPU & exposes degraded camera? \\", r"\midrule"]
    for _, r in d.iterrows():
        tex.append(f"{LBL.get(r['metric'], r['metric']):8s} & ${r.allgpu_value:.3f}$ & "
                   f"${r.allnpu_value:.3f}$ & {r.exposes_failed_camera} \\\\")
    tex += [r"\bottomrule", r"\end{tabular}"]
    backup_stale(PKG / "metric_sensitivity.tex")
    (PKG / "metric_sensitivity.tex").write_text("\n".join(tex) + "\n")
    print("table_metric_sensitivity:")
    for _, r in d.iterrows():
        print(f"  {r['metric']:7s} {r.allgpu_value:.3f}/{r.allnpu_value:.3f} {r.exposes_failed_camera}")
    return True


if __name__ == "__main__":
    main()
