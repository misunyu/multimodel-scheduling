"""fig:persize-sweep + commented tab:persize-contention + tab:persize-npu. rev30-based.
Source: rev30_clean_resnet/rev30_persize.csv (All-GPU per-size loss vs no contention),
        rev30_clean_resnet/rev30_canonical.csv (All-NPU per-size across k)."""
from __future__ import annotations
import sys
import pandas as pd
sys.path.insert(0, str(__import__("pathlib").Path(__file__).resolve().parent))
from _common import RES, RD, backup_stale

R30 = RES / "rev30_clean_resnet"
PKG = RD / "table4_persize"
# paper appendix rows use k=1,2,4,8 (approx 24/45/56/67% GPU skip)
ROWS = [(1, r"$\approx24\%$"), (2, r"$\approx45\%$"), (4, r"$\approx56\%$"), (8, r"$\approx67\%$")]


def main():
    ps = pd.read_csv(R30 / "rev30_persize.csv").set_index("k")
    c = pd.read_csv(R30 / "rev30_canonical.csv")
    c["ratio"] = c.placement.apply(lambda s: s.count("N"))
    an = c[(c.group == "N4") & (c.ratio == 4)]
    npu = an.groupby("k").agg(s=("sap_small", "mean"), m=("sap_medium", "mean"),
                              l=("sap_large", "mean"))

    PKG.mkdir(exist_ok=True)
    backup_stale(PKG / "persize_under_contention.csv")
    ps.reset_index().to_csv(PKG / "persize_under_contention.csv", index=False)
    npu.reset_index().to_csv(PKG / "persize_npu.csv", index=False)

    # tab:persize-contention (All-GPU per-size loss)
    t1 = [r"% regenerated by regen_table4_persize.py (tab:persize-contention)",
          r"\begin{tabular}{lccc}", r"\toprule",
          r"GPU deadline-miss rate & Small & Medium & Large \\", r"\midrule"]
    for k, lbl in ROWS:
        r = ps.loc[k]
        t1.append(f"{lbl} & ${r.loss_small:.3f}$ & ${r.loss_medium:.3f}$ & ${r.loss_large:.3f}$ \\\\")
    t1 += [r"\bottomrule", r"\end{tabular}"]
    backup_stale(PKG / "table4.tex")
    (PKG / "table4.tex").write_text("\n".join(t1) + "\n")

    # tab:persize-npu (All-NPU per-size flat)
    t2 = [r"% regenerated by regen_table4_persize.py (tab:persize-npu)",
          r"\begin{tabular}{lccc}", r"\toprule", r"$k$ & Small & Medium & Large \\", r"\midrule"]
    for k in [0, 1, 2, 3, 4, 6, 8]:
        r = npu.loc[k]
        t2.append(f"${k}$ & ${r.s:.4f}$ & ${r.m:.4f}$ & ${r.l:.4f}$ \\\\")
    t2 += [r"\bottomrule", r"\end{tabular}"]
    (PKG / "table4_persize_npu.tex").write_text("\n".join(t2) + "\n")

    print("table4_persize (All-GPU loss):")
    for k, lbl in ROWS:
        r = ps.loc[k]
        print(f"  k={k} {lbl}: {r.loss_small:.3f}/{r.loss_medium:.3f}/{r.loss_large:.3f}")
    print(f"  All-NPU per-size max range: s={npu.s.max()-npu.s.min():.4f} "
          f"m={npu.m.max()-npu.m.min():.4f} l={npu.l.max()-npu.l.min():.4f} (flat)")
    return True


if __name__ == "__main__":
    main()
