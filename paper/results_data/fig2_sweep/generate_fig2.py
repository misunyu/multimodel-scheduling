#!/usr/bin/env python3
"""Fig.2 (fig:sweep) generator — contention sweep, worst-stream sAP vs GPU skip.

Source : sweep_byN_points.csv  (copied from accv_experiments/results/rev24_sweep_byN_points.csv)
         threads=4 both devices, mxq b2441f9d, global8, yolo11s, 3 reps/point, ResNet50 GPU lever.
Output : fig2_sweep.tex  (pgfplots \addplot coordinate blocks, identical to paper fig:sweep)
         fig2_sweep.png  (matplotlib preview)
Cross-validates the generated coordinates against paper/main_vision.tex fig:sweep block.

Extraction only; no new measurement. Generated by rev-package build.
"""
import sys
from pathlib import Path
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = Path(__file__).resolve().parent
TEX_PAPER = HERE.parent.parent / "main_vision.tex"
NPU_FLAT = 0.0836

def coords(df, N):
    s = df[(df.N == N)].sort_values("gpu_skip")
    s = s.drop_duplicates("gpu_skip")
    return [(round(r.gpu_skip, 1), round(r.allgpu_worst, 4)) for _, r in s.iterrows()]

def fmt(pts):
    return "".join(f"({g:g},{w:.4f})" for g, w in pts)

def main():
    df = pd.read_csv(HERE / "sweep_byN_points.csv")
    c2, c4, c8 = coords(df, 2), coords(df, 4), coords(df, 8)
    tex = []
    tex.append("% Fig.2 fig:sweep -- regenerated from sweep_byN_points.csv (rev24). Do not hand-edit.")
    tex.append(r"\addplot[red,    mark=*]         coordinates {" + fmt(c2) + "};")
    tex.append(r"\addlegendentry{All-GPU $N{=}2$}")
    tex.append(r"\addplot[orange, mark=square*]   coordinates {" + fmt(c4) + "};")
    tex.append(r"\addlegendentry{All-GPU $N{=}4$}")
    tex.append(r"\addplot[brown,  mark=triangle*] coordinates {" + fmt(c8) + "};")
    tex.append(r"\addlegendentry{All-GPU $N{=}8$}")
    tex.append(r"\addplot[blue, dashed, mark=none] coordinates {(0,%.4f)(90,%.4f)};" % (NPU_FLAT, NPU_FLAT))
    tex.append(r"\addlegendentry{All-NPU (all $N$)}")
    (HERE / "fig2_sweep.tex").write_text("\n".join(tex) + "\n")

    # preview PNG
    fig, ax = plt.subplots(figsize=(5.2, 2.9))
    for pts, lab, col, mk in [(c2, "All-GPU N=2", "red", "o"), (c4, "All-GPU N=4", "orange", "s"),
                               (c8, "All-GPU N=8", "brown", "^")]:
        xs, ys = zip(*pts); ax.plot(xs, ys, marker=mk, color=col, lw=1.8, ms=4, label=lab)
    ax.axhline(NPU_FLAT, ls="--", color="blue", label="All-NPU (all N)")
    ax.axvspan(0, 90, ymin=0, ymax=0, alpha=0)
    ax.axvline(48, ls=":", color="gray"); ax.text(48, 0.112, "crossover ≈48%", fontsize=8, color="gray")
    ax.set_xlabel("GPU frame skip (%)"); ax.set_ylabel("worst-stream sAP")
    ax.set_xlim(0, 90); ax.set_ylim(0.045, 0.122); ax.grid(True, alpha=0.3); ax.legend(fontsize=7, ncol=2)
    fig.tight_layout(); fig.savefig(HERE / "fig2_sweep.png", dpi=130); fig.savefig(HERE / "fig2_sweep.pdf")
    plt.close(fig)

    # cross-validate against paper
    paper = TEX_PAPER.read_text()
    ok = True; misses = []
    for pts in (c2, c4, c8):
        for g, w in pts:
            tok = f"({g:g},{w:.4f})"
            if tok not in paper:
                ok = False; misses.append(tok)
    print(f"Fig2: generated coords N2={len(c2)} N4={len(c4)} N8={len(c8)} points")
    print(f"Fig2 cross-check vs main_vision.tex: {'PASS' if ok else 'FAIL'}" + ("" if ok else f"  missing {misses[:5]}"))
    return ok

if __name__ == "__main__":
    sys.exit(0 if main() else 1)
