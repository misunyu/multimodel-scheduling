"""fig:sweeps (Fig 3: fig:sweep + fig:split). rev30-based.
  fig:sweep  (a): All-GPU N=2/4/8 worst vs gpu_skip + flat All-NPU -> rev30_fig3a_points.csv
  fig:split  (b): All-GPU / All-NPU / Oracle (N=4) vs gpu_skip     -> rev30_oracle_by_contention.csv
Emits addplot coordinate blocks and cross-checks each coordinate against the paper tikz.
"""
from __future__ import annotations
import re
import sys
import pandas as pd
sys.path.insert(0, str(__import__("pathlib").Path(__file__).resolve().parent))
from _common import RES, RD, backup_stale, paper_text

R30 = RES / "rev30_clean_resnet"
PKG = RD / "fig2_sweep"


def coords(pairs):
    return "".join(f"({x},{y:.4f})" for x, y in pairs)


def _paper_series_map():
    """label -> [(x,y)] from non-commented \\addplot ... coordinates {...} lines, pairing
    each with the following \\addlegendentry. Label extracted by slicing (handles $N{=}2$)."""
    out, pending = {}, None
    for raw in paper_text().splitlines():
        line = raw.strip()
        if line.startswith("%"):
            continue
        if "coordinates" in line and line.startswith(r"\addplot"):
            i, j = line.find("{"), line.rfind("}")
            if i >= 0 and j > i:
                pending = [(float(a), float(b)) for a, b in re.findall(r"\(([\d.]+),([\d.]+)\)", line[i:j])]
        elif line.startswith(r"\addlegendentry") and pending is not None:
            lbl = line[line.find("{") + 1:line.rfind("}")]
            out.setdefault(lbl, []).extend(pending)  # merge occurrences (label repeats across subfigures)
            pending = None
    return out


def parse_paper_series(label):
    return _paper_series_map().get(label, [])


def main():
    f3a = pd.read_csv(R30 / "rev30_fig3a_points.csv")
    orc = pd.read_csv(R30 / "rev30_oracle_by_contention.csv")

    # --- Fig 3a: All-GPU per N ---
    series_a = {}
    for N, tag in [(2, r"All-GPU $N{=}2$"), (4, r"All-GPU $N{=}4$"), (8, r"All-GPU $N{=}8$")]:
        sub = f3a[(f3a.N == N) & f3a.allgpu_worst.notna()].sort_values("gpu_skip_mean")
        series_a[tag] = [(round(r.gpu_skip_mean, 1), r.allgpu_worst) for r in sub.itertuples()]
    npu_flat = f3a[f3a.allnpu_worst.notna()].allnpu_worst.mean()

    # --- Fig 3b: N=4 All-GPU / All-NPU / Oracle ---
    series_b = {
        "All-GPU": [(round(r.gpu_skip_allgpu, 1), r.allgpu_worst) for r in orc.itertuples()],
        "All-NPU": [(round(r.gpu_skip_allgpu, 1), r.allnpu_worst) for r in orc.itertuples()],
        "Oracle": [(round(r.gpu_skip_allgpu, 1), r.oracle_worst) for r in orc.itertuples()],
    }

    # emit tex (both subfigures' addplot bodies)
    lines = [r"% regenerated by regen_fig2_sweep.py from rev30 -- do not hand-edit.",
             r"% ---- Fig 3a (fig:sweep): homogeneous N=2,4,8 ----"]
    for tag, pts in series_a.items():
        lines += [f"\\addplot coordinates {{{coords(pts)}}};", f"\\addlegendentry{{{tag}}}"]
    lines += [f"\\addplot[blue,dashed] coordinates {{(0,{npu_flat:.4f})(84,{npu_flat:.4f})}};",
              r"\addlegendentry{All-NPU}",
              r"% ---- Fig 3b (fig:split): N=4 All-GPU / All-NPU / Oracle ----"]
    for tag, pts in series_b.items():
        lines += [f"\\addplot coordinates {{{coords(pts)}}};", f"\\addlegendentry{{{tag}}}"]
    backup_stale(PKG / "fig2_sweep.tex")
    (PKG / "fig2_sweep.tex").write_text("\n".join(lines) + "\n")

    # CSV
    backup_stale(PKG / "sweep_byN_points.csv")
    f3a.to_csv(PKG / "sweep_byN_points.csv", index=False)
    orc.to_csv(PKG / "oracle_by_contention.csv", index=False)

    # cross-check vs paper tikz, coordinate by coordinate
    mism = []
    checks = [("All-GPU $N{=}2$", series_a[r"All-GPU $N{=}2$"]),
              ("All-GPU $N{=}4$", series_a[r"All-GPU $N{=}4$"]),
              ("All-GPU $N{=}8$", series_a[r"All-GPU $N{=}8$"])]
    for label, gen in checks:
        paper_pts = parse_paper_series(label)
        for (gx, gy) in gen:
            hit = any(abs(gx - px) <= 0.15 and abs(gy - py) <= 5e-4 for px, py in paper_pts)
            if not hit:
                mism.append((label, gx, round(gy, 4)))
    # Fig 3b series (All-GPU/All-NPU/Oracle appear in split subfig)
    for label in ["All-GPU", "All-NPU", "Oracle"]:
        paper_pts = parse_paper_series(label)
        for (gx, gy) in series_b[label]:
            if paper_pts and not any(abs(gx - px) <= 0.15 and abs(gy - py) <= 5e-4 for px, py in paper_pts):
                mism.append((f"split/{label}", gx, round(gy, 4)))

    print("fig2_sweep: N=4 All-GPU", [f"({x},{y:.4f})" for x, y in series_b["All-GPU"]])
    print("           Oracle     ", [f"({x},{y:.4f})" for x, y in series_b["Oracle"]])
    print(f"  coordinate cross-check vs paper tikz: {'PASS' if not mism else 'MISMATCH '+str(mism)}")
    return not mism


if __name__ == "__main__":
    main()
