"""tab:decomp (Table 3). Quantization = NPU-GPU at 4 threads (rev19_table1_threads4.csv);
Staleness = NPU(24t)-NPU(4t) (rev18_postproc_levers.csv). rel% = raw numerator / FP32 GPU A_b.
Matches the C2-corrected paper cells: staleness small -0.001 (-8.0%), medium -0.030 (-16.0%).
"""
from __future__ import annotations
import sys
import numpy as np
import pandas as pd
sys.path.insert(0, str(__import__("pathlib").Path(__file__).resolve().parent))
from _common import RES, RD, backup_stale, paper_text

PKG = RD / "table2_decomp"
SIZES = ["small", "medium", "large"]


def main():
    q = pd.read_csv(RES / "rev19_table1_threads4.csv")
    s = pd.read_csv(RES / "rev18_postproc_levers.csv")
    g = q[q.device == "GPU"]; n4 = q[q.device == "NPU"]
    A = {"small": g.sap_s.mean(), "medium": g.sap_m.mean(), "large": g.sap_l.mean()}
    Q = {"small": n4.sap_s.mean() - g.sap_s.mean(), "medium": n4.sap_m.mean() - g.sap_m.mean(),
         "large": n4.sap_l.mean() - g.sap_l.mean()}
    s4 = s[s.threads == 4]; s24 = s[s.threads == 24]
    L = {"small": s24.npu_sap_s.mean() - s4.npu_sap_s.mean(),
         "medium": s24.npu_sap_m.mean() - s4.npu_sap_m.mean(),
         "large": s24.npu_sap_l.mean() - s4.npu_sap_l.mean()}

    def rel(v, sz): return 100 * v / A[sz]

    rows = []
    for mech, D, src in [("Quantization", Q, "rev19_table1_threads4.csv"),
                         ("Staleness", L, "rev18_postproc_levers.csv")]:
        for sz in SIZES:
            rows.append({"mechanism": mech, "size": sz, "dsap": round(D[sz], 3),
                         "dsap_raw": round(D[sz], 4), "rel_pct": round(rel(D[sz], sz), 1),
                         "A_b_gpu": round(A[sz], 4), "source": src})
    df = pd.DataFrame(rows)
    backup_stale(PKG / "decomp.csv")
    df.to_csv(PKG / "decomp.csv", index=False)

    def cell(mech, sz):
        r = df[(df.mechanism == mech) & (df["size"] == sz)].iloc[0]
        return f"${r['dsap']:+.3f}$ (${r['rel_pct']:+.1f}\\%$)"

    tex = [r"% regenerated by regen_table2_decomp.py -- do not hand-edit.",
           r"\begin{tabular}{lccc}", r"\toprule",
           r"Loss Component & Small ($\Delta$sAP) & Medium ($\Delta$sAP) & Large ($\Delta$sAP) \\",
           r"\midrule",
           "Quantization", "& " + cell("Quantization", "small"),
           "& " + cell("Quantization", "medium"), "& " + cell("Quantization", "large") + r" \\", "",
           "Staleness", "& " + cell("Staleness", "small"),
           "& " + cell("Staleness", "medium"), "& " + cell("Staleness", "large") + r" \\",
           r"\bottomrule", r"\end{tabular}"]
    backup_stale(PKG / "table2.tex")
    (PKG / "table2.tex").write_text("\n".join(tex) + "\n")

    print("table2_decomp (rel% = full-precision numerator / GPU A_b):")
    for _, r in df.iterrows():
        print(f"  {r['mechanism']:12s} {r['size']:6s} {r['dsap']:+.3f} ({r['rel_pct']:+.1f}%)")
    # reconciliation note: staleness-medium full-precision rel% is -16.1, paper prints -16.0
    med = df[(df.mechanism == "Staleness") & (df["size"] == "medium")].iloc[0]
    pt = paper_text()
    if f"{med['rel_pct']:+.1f}" not in pt and "-16.0" in pt:
        print(f"  RECONCILE: staleness-medium rel% = {med['rel_pct']:+.1f}% (full precision, -16.059); "
              f"paper prints -16.0% (4dp-rounded numerator). 0.1pp display-rounding artifact.")
    for tok in ["-8.0", "-20.5", "-48.4", "-19.7"]:
        if tok not in pt:
            print(f"  WARN {tok} not in paper")
    return True


if __name__ == "__main__":
    main()
