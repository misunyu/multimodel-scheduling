"""Phase N2-A A1: campaign schedules and the fixed run order (written before the campaign).

Schedules: 11 families x k in {1,2,3,4}, beta 0.25, rate = beta * Cmax[model] * k (gen_schedules_npu.build_family; Cmax from
revision_profiling_npu/isolated/offline_profile.json) -> revision_profiling_npu/schedules/<family>_x<k>.yaml (44 files).
Order (numpy default_rng(42), one generator used in this sequence):
  rep0 block: permutation of the 11 families; then, family by family in that order, a permutation of its (k, candidate)
              pairs (4 x candidates). 372 runs.
  rep1 block: permutation of the 60 (family, combination) pairs of the 3x N>=3 evaluation set (rbrsyb, rbybys, rsybys,
              rbrsybys). rep2 block: a new permutation of the same 60.
Output: revision_profiling_npu/RUN_PLAN.md and run_plan.csv (order, block, schedule, combination, repeat).

  python3 -B code/run_plan_npu.py
"""
import sys

sys.dont_write_bytecode = True

import csv
from pathlib import Path

import numpy as np
import yaml

from gen_schedules_npu import FAMILIES, build_family, check_all

ROOT = Path(__file__).resolve().parent.parent.parent / "revision_profiling_npu"
BETA = 0.25
MULTS = (1, 2, 3, 4)
EVAL = ("rbrsyb", "rbybys", "rsybys", "rbrsybys")
SEED = 42
SEC_PER_RUN = 40.9          # pilot measurement (REPORT_N1 section 5)


def comb_key(c):
    return int(c.rsplit("_", 1)[1])


def main():
    check_all()
    sd = ROOT / "schedules"
    sd.mkdir(parents=True, exist_ok=True)
    combs, lam = {}, {}
    for fam in FAMILIES:
        for k in MULTS:
            y = build_family(fam, BETA, k)
            (sd / f"{fam}_x{k}.yaml").write_text(yaml.safe_dump(y, sort_keys=False))
            combs[fam] = sorted(y["combinations"], key=comb_key)
            first = next(iter(y["combinations"].values()))["instances"]
            lam[(fam, k)] = {n: round(v["rate"], 4) for n, v in first.items()}
    rng = np.random.default_rng(SEED)
    rows = []
    fam_order = [FAMILIES[i] for i in rng.permutation(len(FAMILIES))]
    for fam in fam_order:
        pairs = [(k, c) for k in MULTS for c in combs[fam]]
        for i in rng.permutation(len(pairs)):
            k, c = pairs[i]
            rows.append(("rep0", f"schedules/{fam}_x{k}.yaml", c, 0))
    ev = [(fam, c) for fam in EVAL for c in combs[fam]]
    assert len(ev) == 60, len(ev)
    for rep in (1, 2):
        for i in rng.permutation(len(ev)):
            fam, c = ev[i]
            rows.append((f"rep{rep}", f"schedules/{fam}_x3.yaml", c, rep))
    assert len(rows) == 492 and len(set(rows)) == 492
    with open(ROOT / "run_plan.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["order", "block", "schedule", "combination", "repeat"])
        for n, r in enumerate(rows, 1):
            w.writerow((n,) + r)
    L = ["# RUN_PLAN (Phase N2-A) — fixed before the campaign", "",
         f"- beta {BETA}; rate = beta x Cmax[model] x k, k in {list(MULTS)}; Cmax from `isolated/offline_profile.json`",
         "- warm-up 5 s + window 30 s; driver `/workspace/lib` (sha 92ad...); one run = one executor_npu.py process",
         f"- seed {SEED} (`numpy.random.default_rng`), generated by `code/run_plan_npu.py`; full order in `run_plan.csv`", "",
         "## Blocks", "",
         f"1. **rep0**: 372 runs = 93 placements x 4 rates. Family order: {', '.join(fam_order)}; within each family "
         "the (rate, candidate) pairs are permuted.",
         "2. **rep1**: 60 runs, 3x of the N>=3 evaluation set (" + ", ".join(EVAL) + "), permuted; starts after rep0.",
         "3. **rep2**: 60 runs, same set, a new permutation; starts after rep1.", "",
         f"Total 492 runs; estimate 492 x {SEC_PER_RUN} s = {492 * SEC_PER_RUN / 3600:.2f} h (pilot mean incl. overhead).", "",
         "## Failure handling (fixed)", "",
         "- A run is failed if its JSON is missing/incomplete/invalid or any NPU sidecar has Close rc != 0. The failed result is "
         "kept as `*.rejected.<execution_id>.json` and the run is retried once immediately (logged in `results/retries.csv`).",
         "- If the retry also fails, the campaign stops and is reported. DMA32 free pages < 20,000 before a run: stop and report.",
         "- Interruptions: time, cause and resume point in `logs/campaign_sessions.log`; resume skips runs whose JSON is ok.", "",
         "## Rates per workload (req/s, identical for every candidate; asserted)", "",
         "| family | x1 | x2 | x3 | x4 |", "|---|---|---|---|---|"]
    for fam in FAMILIES:
        L.append(f"| {fam} | " + " | ".join(", ".join(f"{n} {v:g}" for n, v in lam[(fam, k)].items()) for k in MULTS) + " |")
    (ROOT / "RUN_PLAN.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[:14]))


if __name__ == "__main__":
    main()
